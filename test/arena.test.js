test('arena: runCli import validates and writes the global summary', () => {
  const src = path.join(tmpRoot, 'upload.json');
  fs.writeFileSync(src, JSON.stringify(arena.buildArenaPayload(SAMPLE_ENTRIES, { now: Date.parse('2026-11-10T00:00:00.000Z') })));
  const { code } = capture(() => arena.runCli(['import', '--from', src]));
  assert.equal(code, 0);
  const written = JSON.parse(fs.readFileSync(arena.globalSummaryPath(), 'utf8'));
  assert.equal(written.by_kind_model.docs.modelx.count, 3);

  const bad = path.join(tmpRoot, 'bad.json');
  fs.writeFileSync(bad, '{"nope": true}');
  const r = capture(() => arena.runCli(['import', '--from', bad]));
  assert.equal(r.code, 1);
});

