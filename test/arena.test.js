test('advisor: community fallback supplies a pass rate below 5 local runs', () => {
  const dir = fs.mkdtempSync(path.join(tmpRoot, 'advisor-'));
  const summaryFile = path.join(dir, 'summary.json');
  const modelsFile = path.join(dir, 'models.json');
  const globalFile = path.join(dir, 'global-summary.json');
  fs.writeFileSync(summaryFile, JSON.stringify({
    by_kind: {
      docs: {
        count: 2,
        first_try_pass_rate: 50,
        by_model: { modelx: { count: 2, first_try_pass_rate: 50 } },
      },
    },
  }));
  fs.writeFileSync(modelsFile, JSON.stringify({ fast: 'modelx' }));
  fs.writeFileSync(globalFile, JSON.stringify({
    schema: 1,
    by_kind_model: { docs: { modelx: { count: 11, first_try_pass_rate: 90.9, avg_cost_usd: 0.03 } } },
  }));

  const saved = {
    ROOSTR_SUMMARY: process.env.ROOSTR_SUMMARY,
    CREW_BOARD_MODELS: process.env.CREW_BOARD_MODELS,
    ROOSTR_GLOBAL_SUMMARY: process.env.ROOSTR_GLOBAL_SUMMARY,
  };
  process.env.ROOSTR_SUMMARY = summaryFile;
  process.env.CREW_BOARD_MODELS = modelsFile;
  process.env.ROOSTR_GLOBAL_SUMMARY = globalFile;
  try {
    const rec = advisor.recommend('fix the readme typos and formatting');
    assert.equal(rec.kind, 'docs');
    assert.equal(rec.recommendedModel, 'modelx');
    assert.equal(rec.community.count, 11);
    assert.equal(rec.modelStats.configured.source, 'community');
    assert.equal(rec.modelStats.configured.passRate, 90.9);

    const direct = advisor.communityModelStat('docs', 'modelx');
    assert.equal(direct.passRate, 90.9);
    assert.equal(direct.confidence, 'community');

    // Below the community sample floor, no fallback is offered.
    assert.equal(advisor.communityModelStat('docs', 'unknown-model'), null);
  } finally {
    for (const [k, v] of Object.entries(saved)) {
      if (v === undefined) delete process.env[k];
      else process.env[k] = v;
    }
  }
});
