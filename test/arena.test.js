test('arena: buildArenaPayload buckets by kind, tool, model, effort', () => {
  const payload = arena.buildArenaPayload(SAMPLE_ENTRIES, { days: 30, now: Date.parse('2026-11-10T00:00:00.000Z') });
  assert.equal(payload.schema, 1);
  assert.equal(payload.days, 30);
  assert.equal(payload.anonId.length, 12);
  assert.ok(payload.buckets.length >= 2);

  const docs = payload.buckets.find((b) => b.kind === 'docs' && b.model === 'modelx');
  assert.ok(docs);
  assert.equal(docs.tool, 'claude');
  assert.equal(docs.effort, 'low');
  assert.equal(docs.runs, 3);
  assert.equal(docs.firstTryPasses, 1);
  assert.equal(docs.passRate, 33.3);
  assert.equal(docs.reworkSum, 3);
  assert.equal(docs.avgRework, 1);
  assert.equal(docs.costUsdSum, 0.6);
  assert.equal(docs.avgCostPerPassUsd, 0.6);
  assert.equal(docs.durationSecSum, 110);

  const tests = payload.buckets.find((b) => b.kind === 'tests');
  assert.ok(tests);
  assert.equal(tests.passRate, 100);
});

test('arena: payload strips repo, path, task, pane and env data', () => {
  const payload = arena.buildArenaPayload(SAMPLE_ENTRIES, { now: Date.parse('2026-11-10T00:00:00.000Z') });
  const text = JSON.stringify(payload);
  for (const secret of ['secret-repo', 'secret thing', 'secret again', '/tmp/secret/file.js', 'w1:p1', 'SECRET_TOKEN']) {
    assert.ok(!text.includes(secret), `payload leaked ${secret}`);
  }
  const allowed = ['kind', 'tool', 'model', 'effort', 'runs', 'firstTryPasses', 'passRate', 'reworkSum', 'avgRework', 'costUsdSum', 'avgCostPerPassUsd', 'durationSecSum'];
  for (const b of payload.buckets) {
    assert.deepEqual(Object.keys(b).sort(), allowed.slice().sort());
  }
});

